export function readUiLang() {
  try {
    const s = localStorage.getItem("msc_lang");
    if (s === "ko" || s === "en") return s;
  } catch {}
  return "en";
}

export function readSummaryLang(fallback = "en") {
  try {
    const s = localStorage.getItem("msc_sum_lang");
    if (SUMMARY_LANGS.some((l) => l.code === s)) return s;
  } catch {}
  return fallback;
}
